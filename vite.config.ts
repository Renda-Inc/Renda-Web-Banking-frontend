import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { defineConfig, type Plugin } from "vite";
import { tanstackStart } from "@tanstack/react-start/plugin/vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import tsconfigPaths from "vite-tsconfig-paths";
import { nitro } from "nitro/vite";

// Standalone build configuration. The app previously ran through a vendor
// vite wrapper; this file wires the same plugins directly so the project
// builds anywhere with no lock-in:
//   tailwindcss, tsconfig paths, TanStack Start (server entry src/server.ts),
//   nitro on production builds (cloudflare-module default preset), React,
//   plus the prerender preview shim described below.

// ---------------------------------------------------------------------------
// Prerender preview shim
//
// When TanStack Start prerenders (SPA mode), its preview server imports the
// built server from <build outDir>/server/server.js. Nitro, however, emits
// its server entry at .output/server/index.mjs, so the preview server finds
// nothing and prerendering fails. These two plugins bridge the gap: the
// first writes a small server.js in the expected location that re-exports
// nitro's entry (with the Cloudflare env/ctx shape it expects), and the
// second removes it once prerendering has run. Both are build-only and the
// shim file never ships.
// ---------------------------------------------------------------------------

const SHIM_MARKER = "// Generated by vite.config.ts for the prerender preview server.";
const shimState: { file: string | undefined } = { file: undefined };

function prerenderShimSource(vars: Record<string, unknown>, entrySpecifier: string) {
  return `${SHIM_MARKER}
import server from "${entrySpecifier}";

const env = ${JSON.stringify(vars)};
const ctx = { waitUntil() {}, passThroughOnException() {}, props: {} };

export default {
  fetch(request) {
    // srvx's NodeRequest exposes \`ip\` as a getter-only accessor and nitro's
    // cloudflare module handler assigns to it; shadow it with a writable one.
    Object.defineProperty(request, "ip", { value: undefined, writable: true, configurable: true });
    return server.fetch(request, env, ctx);
  },
};
`;
}

function prerenderPreviewShim(): Plugin {
  let root = process.cwd();
  // The preview server resolves its server bundle as
  // join(build.outDir ?? "dist", "server") plus the server entry name. This
  // config sets neither build.outDir nor a custom entry name, so the target
  // is dist/server/server.js. If either ever changes in this file, update
  // these constants to match.
  const serverEntryName = "server";
  const shimDir = join("dist", "server");
  return {
    name: "renda-web-prerender-preview-shim",
    apply: "build",
    configResolved(config) {
      root = config.root;
    },
    buildApp: {
      order: "post",
      async handler() {
        const candidates = [join(".output", "server"), shimDir];
        let entryDir: string | undefined;
        for (const candidate of candidates) {
          const resolved = resolve(root, candidate);
          try {
            await access(join(resolved, "index.mjs"));
            entryDir = resolved;
            break;
          } catch {
            // keep looking
          }
        }
        if (!entryDir) {
          console.warn(
            `[renda-web] Cannot prerender: nitro's index.mjs is in none of ${candidates.join(", ")}, so the preview shim was not written and prerendered routes will fall back to SSR.`,
          );
          return;
        }
        const entryName = basename(serverEntryName, extname(serverEntryName));
        if (!entryName || (entryName === "index" && resolve(root, shimDir) === entryDir)) {
          console.warn(
            `[renda-web] Cannot prerender: the server entry "${serverEntryName}" would need a shim that outranks nitro's own entry. Rename the entry to anything but "index".`,
          );
          return;
        }
        const target = join(resolve(root, shimDir), `${entryName}.js`);
        const occupant = await readFile(target, "utf8").catch(() => undefined);
        if (occupant !== undefined && !occupant.startsWith(SHIM_MARKER)) {
          console.warn(
            `[renda-web] Cannot prerender: ${entryName}.js already exists in ${shimDir} and was not written by this plugin.`,
          );
          return;
        }
        let vars: Record<string, unknown> = {};
        try {
          const parsed = JSON.parse(await readFile(join(entryDir, "wrangler.json"), "utf8"))?.vars;
          if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) vars = parsed;
        } catch {
          // no wrangler vars to forward
        }
        const specifier = relative(resolve(root, shimDir), join(entryDir, "index.mjs"))
          .split(sep)
          .join("/");
        await mkdir(resolve(root, shimDir), { recursive: true });
        await writeFile(
          target,
          prerenderShimSource(vars, specifier.startsWith(".") ? specifier : `./${specifier}`),
        );
        shimState.file = target;
      },
    },
  };
}

function prerenderPreviewShimCleanup(): Plugin {
  return {
    name: "renda-web-prerender-preview-shim-cleanup",
    apply: "build",
    enforce: "post",
    buildApp: {
      order: "post",
      async handler() {
        if (!shimState.file) return;
        await rm(shimState.file, { force: true });
        shimState.file = undefined;
      },
    },
  };
}

export default defineConfig(({ command }) => ({
  plugins: [
    tailwindcss(),
    tsconfigPaths({ projects: ["./tsconfig.json"] }),
    tanstackStart({
      // Redirect TanStack Start's bundled server entry to src/server.ts
      // (our SSR error wrapper). Nitro builds from this.
      server: { entry: "server" },
      importProtection: {
        behavior: "error",
        client: {
          files: ["**/server/**"],
          specifiers: ["server-only"],
        },
      },
    }),
    ...(command === "build"
      ? [nitro({ defaultPreset: "cloudflare-module" }), prerenderPreviewShim(), prerenderPreviewShimCleanup()]
      : []),
    react(),
  ],
  resolve: {
    alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) },
    dedupe: [
      "react",
      "react-dom",
      "react/jsx-runtime",
      "react/jsx-dev-runtime",
      "@tanstack/react-query",
      "@tanstack/query-core",
    ],
  },
  optimizeDeps: {
    include: ["react", "react-dom", "react-dom/client", "react/jsx-runtime", "react/jsx-dev-runtime"],
    ignoreOutdatedRequests: true,
  },
  server: { host: "::", port: 8080 },
}));
